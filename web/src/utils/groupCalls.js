// ---------------------------------------------------------------------------
// Групповые звонки (см. contexts/GroupCallContext.jsx, firestore.rules ->
// groupCalls/{callId}).
//
// Устройство такое же клиентское, как и у личных звонков: бэкенда нет
// (бесплатный план Firebase), поэтому сигнализация — документы Firestore, а
// сам звук/видео идут напрямую между браузерами (WebRTC). Разница в том, что
// участников больше двух, и соединения строятся "каждый с каждым" (mesh): у
// человека в звонке из N человек одновременно N-1 отдельных
// RTCPeerConnection. Сервера-микшера (SFU), который принимал бы один поток и
// раздавал остальным, тут просто негде разместить.
//
// Отсюда два практических потолка:
//   • MAX_PARTICIPANTS — жёсткий предел на звонок. 20 человек — это 19
//     исходящих аудио-потоков с каждого устройства; на слабом телефоне это
//     уже край, поэтому больше не пускаем.
//   • MAX_VIDEO_PARTICIPANTS — с какого размера звонка камера отключается
//     совсем. Видео в mesh дороже голоса примерно на порядок, и на 20
//     участниках оно кладёт и сеть, и процессор — поэтому кнопка камеры
//     доступна только в небольших звонках.
// ---------------------------------------------------------------------------

import { canInGroup } from "./groupRoles";

export const MAX_PARTICIPANTS = 20;
export const MAX_VIDEO_PARTICIPANTS = 6;

// Сколько ждём ответа у тех, кому дозваниваемся, прежде чем убрать их из
// "звоним" (звонок при этом продолжается — он живёт как комната, см. ниже).
export const GROUP_RING_TIMEOUT_MS = 45000;

// Как часто участник подтверждает "я ещё здесь"
// (groupCalls/{id}/presence/{uid}.at) и через сколько молчания его можно
// вычистить из звонка. Без этого закрытая вкладка оставляла бы "призрака" в
// списке участников, а группе доставалась бы вечная плашка "идёт звонок",
// которую некому погасить: правила разрешают убрать из participants только
// самого себя.
//
// Отметки живут ОТДЕЛЬНЫМИ документами, а не полем в документе звонка: иначе
// каждые пару секунд переписывался бы сам звонок, и его снапшот прилетал бы
// всем участникам и всем, у кого открыт чат группы (лишние чтения на
// бесплатном плане плюс дёрганый интерфейс).
//
// Порог заведомо больше периода отметок — чтобы обычная задержка сети никого
// не выкидывала. Те же 90 секунд продублированы в firestore.rules.
// Сколько ждём, пока соединение с конкретным участником встанет, прежде чем
// пересобрать его заново. Mesh на Firestore держится на обмене документами:
// потерялся один снапшот (спящая вкладка, обрыв, отказ правил в момент входа)
// — и соединение зависает в "Соединяем…" НАВСЕГДА, потому что переспросить
// некому. Поэтому не ждём вечно: пересобираем попытку с нуля, новый offer в
// новом документе. 12 секунд — с запасом больше обычного ICE-хендшейка даже
// через TURN (1-3 с), так что нормальные соединения этого таймера не увидят.
// Сколько ждём подтверждения собственного входа в звонок. Транзакция уже
// прошла, но пока обновлённый документ не доехал обратно, экран звонка
// держится "на честном слове". Если за это время подтверждения так и нет —
// честнее выйти с объяснением, чем показывать звонок, которого нет.
export const JOIN_CONFIRM_TIMEOUT_MS = 20000;

export const PEER_CONNECT_TIMEOUT_MS = 12000;
// Больше трёх попыток подряд смысла нет: если не вышло, дело не в потерянном
// сообщении, а в сети — тогда честнее показать ошибку, чем крутить вечность.
export const MAX_PEER_ATTEMPTS = 3;

export const HEARTBEAT_MS = 30000;
export const STALE_PARTICIPANT_MS = 90000;

// Протухла ли отметка участника. at — Timestamp из Firestore; отсутствие
// отметки тоже считаем протухшей (человек ушёл ещё до того, как отметки
// появились, или его клиент их не пишет).
export function isStaleParticipant(at, now = Date.now()) {
  const ms = at?.toMillis?.() ?? (typeof at === "number" ? at : null);
  if (!ms) return true;
  return now - ms > STALE_PARTICIPANT_MS;
}

// Живой ли звонок: есть ли в нём хоть один участник, чья отметка свежая.
// presence — { uid: Timestamp } (см. GroupCallContext.jsx -> readPresence).
//
// Только что созданный звонок считаем живым независимо от отметок: между
// созданием документа и первой отметкой его автора проходит один сетевой
// обмен, и без этой поблажки чужая вкладка успевала бы закрыть звонок как
// "мёртвый" через долю секунды после начала.
export function hasLiveParticipant(call, presence) {
  const participants = call?.participants || [];
  if (!participants.length) return false;
  const createdMs = call?.createdAt?.toMillis?.();
  if (!createdMs || Date.now() - createdMs < STALE_PARTICIPANT_MS) return true;
  if (!presence) return true; // отметки ещё не загружены — считаем живым
  return participants.some((uid) => !isStaleParticipant(presence[uid]));
}

// Кто может НАЧАТЬ звонок в группе и дозваниваться остальным.
// По умолчанию — только владелец группы (в проекте это единственная роль
// "админа группы", см. chats/{chatId}.ownerId). Владелец может разрешить то
// же самое всем участникам, включив chats/{chatId}.callByMembers (см.
// ChatWindow.jsx -> управление группой, firestore.rules).
export function canStartGroupCall(chat, uid) {
  if (!chat || !uid || !chat.isGroup) return false;
  if (!Array.isArray(chat.members) || !chat.members.includes(uid)) return false;
  if (chat.ownerId === uid) return true;
  if (chat.callByMembers === true) return true;
  // Администратор группы — если владелец оставил ему это право
  // (см. utils/groupRoles.js).
  return canInGroup(chat, uid, "calls");
}

// Присоединиться к уже идущему звонку может любой участник группы — даже
// тот, кому не звонили (звонок ведёт себя как комната: в чате висит плашка
// "Идёт звонок · присоединиться"). Ограничение только по размеру.
export function canJoinGroupCall(chat, call, uid) {
  if (!chat || !call || !uid) return false;
  if (call.status !== "live") return false;
  if (!Array.isArray(chat.members) || !chat.members.includes(uid)) return false;
  if ((call.participants || []).includes(uid)) return false;
  return (call.participants || []).length < MAX_PARTICIPANTS;
}

// Уже числюсь участником на сервере, хотя локально в звонке меня нет:
// перезагрузили вкладку, экран закрылся из-за сбоя, вход оборвался на
// половине. Раньше кнопка "Присоединиться" в таком состоянии просто гасла
// (canJoinGroupCall возвращает false для тех, кто уже в participants) —
// человек оказывался заперт СНАРУЖИ собственного звонка и не мог войти,
// пока его не вычистят как протухшего, то есть полторы минуты. Теперь для
// него есть отдельная кнопка "Вернуться в звонок".
export function shouldRejoinGroupCall(chat, call, uid) {
  if (!chat || !call || !uid) return false;
  if (call.status !== "live") return false;
  if (!Array.isArray(chat.members) || !chat.members.includes(uid)) return false;
  return (call.participants || []).includes(uid);
}

// "Я сейчас в групповом звонке" — крошечный общий флаг на весь модуль.
// Нужен из-за порядка провайдеров в App.jsx: GroupCallProvider вложен в
// CallProvider, поэтому групповой звонок видит личный через useCall(), а
// личный про групповой узнать не может — вот через этот флаг и узнаёт (см.
// contexts/CallContext.jsx: входящий личный звонок во время группового
// игнорируется так же, как и во время другого личного).
let groupCallBusy = false;

export function setGroupCallBusy(value) {
  groupCallBusy = !!value;
}

export function isGroupCallBusy() {
  return groupCallBusy;
}

// Кто в паре делает offer, а кто отвечает — решается одним и тем же
// сравнением на обоих клиентах: "первый" тот, чей uid меньше. Благодаря
// этому оба, увидев друг друга в списке участников, приходят к одному и тому
// же решению без всяких переговоров и не создают встречные offer'ы
// (классический glare в WebRTC).
export function isOfferer(myUid, otherUid) {
  return myUid < otherUid;
}
