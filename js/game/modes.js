/**
 * Правило равных сторон.
 *
 * Считаются ТОЛЬКО ЛЮДИ. Боты добивают обе стороны поровну и потому прячут
 * перекос: в комнате «один человек против нуля» бойцов будет пять на пять, и
 * по общему числу стороны выглядят одинаковыми. Драться при этом человеку
 * придётся с ботами, а второй пришедший, встав к первому, сделает два на ноль.
 *
 * Отсюда два разных вопроса и два разных ответа:
 *
 *   встать за сторону    — можно, если людей там не больше, чем у соперника.
 *                          При равенстве можно за любую: два на два честно.
 *   перейти на сторону   — можно, только если людей там СТРОГО меньше. При
 *                          равенстве переход сам по себе и создаёт перекос:
 *                          уходишь оттуда, где было поровну, и делаешь 3:1.
 */
export const sideAllowed = (side, people) =>
  (people?.[side] || 0) <= (people?.[otherSide(side)] || 0);

export const canSwitchTo = (side, people) =>
  (people?.[side] || 0) < (people?.[otherSide(side)] || 0);

/** Куда поставить того, кому всё равно: где людей меньше. */
export const thinnerSide = people => ((people?.a || 0) <= (people?.b || 0) ? "a" : "b");

