// karier.js — «Карьер».
//
// Известняковый карьер в три уступа. Несимметричная, вертикальная, с длинными
// простреливаемыми линиями — противоположность «Депо» по всем статьям, и это
// главное в ней. Смысл пары карт в том, чтобы одна и та же тактика на них не
// работала.
//
// Как она устроена и почему:
//
//   Яма.       Три террасы кольцом спускаются к затопленному дну. Кто внизу —
//              видит небо и четыре силуэта над собой; кто наверху — видит всё,
//              но и сам стоит на светлом фоне.
//   Мост.      Ржавый конвейер перекинут через яму поверху. Самый быстрый путь
//              с края на край и самое простреливаемое место на карте разом —
//              на нём негде укрыться, зато он экономит полминуты обхода.
//   Тоннель.   Дренажная труба понизу связывает два дальних угла дна. Длинная,
//              тёмная и полностью безопасная: расплата за безопасность — время.
//   Диспетчерская. Стеклянная будка над верхней террасой. Обзор на пол-карты,
//              но стекло пулю не держит — видно оттуда всех, и тебя тоже.
//
// Точки возрождения разнесены по разным уступам, чтобы двое не появились
// лицом к лицу.

import { MapBuilder, THREE, rough, glass, yawTowards } from "./builder.js";

export const meta = {
  id: "karier",
  name: "Карьер",
  subtitle: "Три уступа, конвейерный мост, длинные линии",
  hint: "Верхняя терраса простреливает полкарты. Тоннель понизу — долго, но живым."
};

const STONE   = 0xb9ab8f;
const STONE_D = 0x8e8168;
const RUST    = 0x8a5a33;
const STEEL   = 0x5c666b;
const SAND    = 0xc9b896;

// Все смотрят в яму: там идёт бой, туда и разворачиваем возрождающихся.
const PIT = [0, 0, 0];
const spawnsFacing = (focus, list) =>
  list.map(pos => ({ pos, yaw: yawTowards(pos, focus) }));

export function build(){
  const b = new MapBuilder();

  // Три оттенка камня — по одному на уступ. Не украшательство: когда вся яма
  // одного цвета, на глаз невозможно определить, на каком ты ярусе и куда
  // ведёт край, по которому ты бежишь.
  const stone1 = rough(0xc6b89c);
  const stone2 = rough(0xb3a68b);
  const stone3 = rough(0xa0937a);
  const stoneD = rough(STONE_D);
  const rust   = rough(RUST, { roughness: 0.8, metalness: 0.25 });
  const steel  = rough(STEEL, { roughness: 0.55, metalness: 0.5 });
  const sand   = rough(SAND);

  // ---- дно ямы ------------------------------------------------------------
  b.box(0, -1, 0, 70, 1, 70, stoneD);

  // мелкая вода — только на вид, ходить по ней можно
  const water = new THREE.Mesh(
    new THREE.PlaneGeometry(40, 40),
    new THREE.MeshStandardMaterial({
      color: 0x5f7d6e, roughness: 0.15, metalness: 0.4,
      transparent: true, opacity: 0.55
    })
  );
  water.rotation.x = -Math.PI / 2;
  water.position.set(0, 0.06, 0);
  b.group.add(water);

  // ---- террасы кольцом ----------------------------------------------------
  // Каждая терраса — четыре плиты по краям, середина остаётся дырой вниз.
  function terrace(inner, outer, y, material){
    const mid = (inner + outer) / 2, w = outer - inner, span = outer * 2;
    b.box(0, 0, -mid, span, y, w, material);
    b.box(0, 0,  mid, span, y, w, material);
    b.box(-mid, 0, 0, w, y, inner * 2, material);
    b.box( mid, 0, 0, w, y, inner * 2, material);
  }
  terrace(35, 48, 6,  stone1);   // нижний уступ
  terrace(48, 60, 12, stone2);   // средний
  terrace(60, 74, 18, stone3);   // верхний, он же край карьера

  // ---- укрытия на уступах -------------------------------------------------
  // Голая терраса — это коридор без единого угла: кто вышел на неё первым,
  // тот и выиграл. Глыбы и обломки плит дают за что спрятаться и ломают
  // длинные простреливаемые линии, не превращая карту в лабиринт.
  const rubble = rough(0x9c9079, { roughness: 0.99 });
  const slab   = rough(0x8d8672, { roughness: 0.98 });

  const covers = [
    // первый уступ (y = 6)
    [-41,  6, -20, 3.4, 1.9, 2.6], [ 41,  6,  36, 3.0, 2.4, 3.0],
    [-20,  6, -41, 2.6, 1.6, 3.4], [ 26,  6,  41, 3.6, 2.1, 2.4],
    [ 41,  6, -40, 2.4, 2.8, 2.4],
    // средний уступ (y = 12)
    [-54,  12,  -8, 3.2, 2.2, 4.0], [ 54, 12,  -34, 3.0, 1.8, 3.0],
    [ -8,  12, -54, 4.0, 2.4, 3.2], [ 30, 12,   54, 3.4, 2.0, 2.6],
    // край карьера (y = 18)
    [-67,  18, -26, 3.0, 2.6, 3.6], [ 67, 18,   14, 3.6, 2.2, 3.0],
    [ 26,  18, -67, 3.4, 2.0, 2.8], [-48, 18,   67, 2.8, 2.4, 3.4]
  ];
  for (const [x, y, z, w, h, d] of covers) b.box(x, y, z, w, h, d, rubble);

  // Пара опрокинутых плит — низкие, из-за них стреляют лёжа и приседая.
  for (const [x, y, z, w, d] of [[-30, 6, 41, 7, 1.6], [54, 12, 36, 1.6, 7], [-34, 18, 64, 7, 1.6]]){
    b.box(x, y, z, w, 1.0, d, slab);
  }

  // ---- подъёмы между уступами --------------------------------------------
  // Каждый подъём стоит СВОЕЙ стороной, и это главное в планировке карьера:
  // чтобы попасть со дна на верхнюю террасу, надо пройти три четверти круга
  // по открытому месту. Кто наверху, успеет увидеть идущего задолго до того,
  // как тот доберётся.
  //
  // Дно -> первый уступ: два подъёма, с севера и с юга, чтобы со дна был
  // выбор и загнать человека в один угол было нельзя.
  // x = 24, а не ближе к середине: дренажный тоннель тянется по дну от x = -36
  // до x = 12, и подъём, поставленный над ним, упирался бы в его стенку —
  // пандус был, а подняться по нему было нельзя.
  b.ramp( 24, 0, -20,  24, 6, -35, 8, stoneD);
  b.ramp(-20, 0,  20, -20, 6,  35, 8, stoneD);

  // Первый -> второй: только с востока.
  b.ramp(35, 6, 20, 48, 12, 20, 8, stoneD);

  // Второй -> третий (край карьера): только с юга.
  b.ramp(10, 12, 48, 10, 18, 60, 8, stoneD);

  // ---- конвейерный мост через яму ----------------------------------------
  // Идёт поверху с одного края верхней террасы на другой.
  b.box(0, 20, 0, 96, 0.6, 6, rust);
  for (let x = -44; x <= 44; x += 8){
    b.box(x, 20.6, -3.1, 1.2, 1.1, 0.4, rust, "decor");   // поручни: не мешают
    b.box(x, 20.6,  3.1, 1.2, 1.1, 0.4, rust, "decor");
  }
  // опоры моста стоят на среднем уступе
  b.box(-52, 12, 0, 2.5, 8, 2.5, steel);
  b.box( 52, 12, 0, 2.5, 8, 2.5, steel);
  // короткие сходни с моста на верхнюю террасу
  // Сходни с моста на верхнюю террасу. base = 17.4: иначе клин пошёл бы от
  // самой земли и наглухо перекрыл проход по среднему уступу под мостом.
  b.ramp(-62, 18, 0, -52, 20.6, 0, 5, steel, 17.4, 10);
  b.ramp( 62, 18, 0,  52, 20.6, 0, 5, steel, 17.4, 10);

  // ---- дренажный тоннель по дну ------------------------------------------
  // Коробка с дыркой: две стены, крышка, открытые торцы.
  const TZ = -26;
  b.box(-12, 0, TZ - 2.6, 48, 3.4, 0.6, stoneD);
  b.box(-12, 0, TZ + 2.6, 48, 3.4, 0.6, stoneD);
  b.box(-12, 3.4, TZ, 48, 0.6, 5.8, stoneD);

  // ---- экскаватор на дне: главное укрытие --------------------------------
  b.box(6, 0, 10, 9, 3.2, 5, rust);            // корпус
  b.box(6, 3.2, 10, 5.5, 2.6, 4, rust);        // кабина
  b.box(-2, 0, 14, 12, 1.1, 2.2, steel);       // опущенная стрела
  b.box(14, 0, 4, 3, 1.6, 3, rust);            // отвалившийся ковш

  // ---- диспетчерская над верхней террасой --------------------------------
  b.box(-66, 18, 52, 3, 7, 3, steel);                    // ножка
  b.box(-66, 25, 52, 9, 0.4, 9, steel);                  // пол будки
  b.box(-66, 25.4, 52, 9, 3, 0.3, glass(), "glass");     // стёкла кругом
  b.box(-66, 25.4, 56.5, 9, 3, 0.3, glass(), "glass");
  b.box(-70.5, 25.4, 52, 0.3, 3, 9, glass(), "glass");
  b.box(-61.5, 25.4, 52, 0.3, 3, 9, glass(), "glass");
  b.box(-66, 28.4, 52, 9.6, 0.4, 9.6, steel);            // крыша
  b.ramp(-66, 18, 44, -66, 25.4, 49.5, 3, steel, 17.6, 12);   // лестница в будку

  // ---- мелочь для ориентации ---------------------------------------------
  // Валуны на дне: то немногое, за чем можно укрыться в самой открытой части
  // карты. Разбросаны неровно — правильная сетка читалась бы как декорация.
  for (const [x, z, w, h, d] of [
    [-30, 24, 2.6, 2.2, 3.0], [  8, -32, 3.0, 1.8, 2.4], [-14, -8, 2.2, 2.6, 2.2],
    [ 18,  22, 3.4, 1.6, 2.8], [-28, -20, 2.4, 2.0, 2.6], [30, 6, 2.0, 2.4, 3.2]
  ]){
    b.box(x, 0, z, w, h, d, sand);
  }
  for (const [x, z] of [[-58, 30], [58, -30]]){
    b.box(x, 18, z, 0.4, 4, 0.4, rust, "decor");   // сигнальные столбики
  }

  b.walls(-78, 78, -78, 78, 60);

  // ---- свет: пыльный полдень ---------------------------------------------
  const sun = new THREE.DirectionalLight(0xffe2b0, 1.9);
  sun.position.set(60, 90, 30);
  sun.castShadow = true;
  sun.shadow.mapSize.set(2048, 2048);
  sun.shadow.bias = -0.0015;
  sun.shadow.camera.left = -90; sun.shadow.camera.right = 90;
  sun.shadow.camera.top = 90;   sun.shadow.camera.bottom = -90;
  sun.shadow.camera.far = 240;
  b.light(sun);
  // Небо светит вниз заметно сильнее, чем кажется правильным "по физике": в
  // карьере половина поверхностей — отвесные стены, отвёрнутые от солнца, и
  // при слабом небесном свете они превращаются в чёрные плоскости, на которых
  // не видно ни уступа, ни человека. Здесь важнее читаемость, чем точность.
  b.light(new THREE.HemisphereLight(0xdff0ff, 0x9a8a68, 1.7));
  b.light(new THREE.AmbientLight(0xffffff, 0.28));

  return {
    group: b.group,
    colliders: b.colliders,
    sky: 0xcfd9de,
    fog: { color: 0xd4d2c4, near: 95, far: 340 },
    // Возрождение. Точки разнесены по всем четырём ярусам и проверены на
    // проходимость: с любой из них можно дойти до любой другой (см. раздел
    // "Проверка карт" в README).
    // Две точки закладки. A — на дне у дренажного тоннеля, куда террористы
    // приходят снизу, а спецназ спускается с уступов. B — на среднем уступе у
    // диспетчерской: туда лезть дольше, зато подход простреливается с моста.
    // Между ними полкарты, и держать обе одним отрядом нельзя — в этом и смысл.
    sites: [[-14, 0.1, -4], [-40, 6.1, -14]],
    spawns: spawnsFacing(PIT, [
      [-25,  0.1,  26],   // дно, юго-запад
      [ 28,  0.1, -14],   // дно, северо-восток
      [-42,  6.1,  10],   // первый уступ
      [ 42,  6.1, -20],   // первый уступ
      [-54, 12.1,  26],   // средний уступ
      [  8, 18.1,  67]    // край карьера
    ]),
    // В командном режиме — низ против верха: одни лезут, другие держат.
    teamSpawns: {
      a: spawnsFacing(PIT, [[-25, 0.1, 26], [28, 0.1, -14]]),
      b: spawnsFacing(PIT, [[-54, 12.1, 26], [8, 18.1, 67]])
    },
    build: b
  };
}
