// plotina.js — «Плотина».
//
// Бетонная плотина малой ГЭС. Это вертикальная карта: если «Теплицы» — про то,
// что тебя видно насквозь, то здесь всё решает высота и то, что спуск с неё
// ровно один на каждом направлении.
//
// Как она устроена:
//
//   Гребень.   Дорога по верху плотины, шестнадцать метров над руслом.
//              Простреливается весь низ — но и сам гребень простреливается с
//              обоих концов насквозь, укрыться там почти негде: парапет по
//              пояс, и всё.
//   Уступы.    Водосливная грань спускается тремя широкими террасами. Каждая —
//              отдельный этаж со своими углами; с верхней видно нижнюю, с
//              нижней верхнюю не видно.
//   Лестницы.  Три сквозных прореза сверху донизу: по центру и по краям. Кто
//              держит прорез — держит этаж. Других путей наверх нет, и это
//              главное решение карты: высоту нельзя взять «где-нибудь сбоку».
//   Машинный зал. Внизу, в русле. Коробка с крышей, два входа и лестница на
//              крышу — единственная высота в низу, откуда отвечают гребню.
//   Водосбросы. Два длинных бетонных канала вдоль краёв: быстрый обход низом
//              без единого укрытия. Добежишь — окажешься сбоку. Не добежишь —
//              сам виноват.
//
// Симметрия зеркальная по x: обе команды получают одинаковые прорезы.

import { MapBuilder, THREE, rough, yawTowards } from "./builder.js";

export const meta = {
  id: "plotina",
  name: "Плотина",
  subtitle: "Гребень, три уступа и машинный зал внизу",
  hint: "Наверх ведут только три прореза. Держи прорез — держишь этаж."
};

const CONCRETE = 0x8c8b81;
const WET      = 0x6a6d68;
const STEEL    = 0x5b6166;
const RUST     = 0x7b5334;
const WATER    = 0x2c5568;

const CREST_Y = 16;
const DAM_X   = 52;             // плотина от -52 до 52 по x
// Прорезы-лестницы: по ним карта и делится. Всё остальное строится «в обход».
const CUTS    = [-30, 0, 30];
const CUT_W   = 6;

const FOCUS = [0, 0, 12];       // русло под плотиной — куда все смотрят
const spawnsFacing = (focus, list) =>
  list.map(pos => ({ pos, yaw: yawTowards(pos, focus) }));

/** Отрезки по x, оставшиеся от [-DAM_X, DAM_X] после вырезания прорезов. */
function spans(){
  const edges = [-DAM_X];
  for (const c of CUTS){ edges.push(c - CUT_W / 2, c + CUT_W / 2); }
  edges.push(DAM_X);
  const out = [];
  for (let i = 0; i < edges.length; i += 2) out.push([edges[i], edges[i + 1]]);
  return out;
}

export function build(){
  const b = new MapBuilder();

  const concrete = rough(CONCRETE, { roughness: 0.95 });
  const wet      = rough(WET, { roughness: 0.75 });
  const steel    = rough(STEEL, { roughness: 0.45, metalness: 0.6 });
  const rust     = rough(RUST, { roughness: 0.85, metalness: 0.2 });
  const water    = new THREE.MeshStandardMaterial({
    color: WATER, roughness: 0.18, metalness: 0.35, transparent: true, opacity: 0.9
  });

  // ---- русло --------------------------------------------------------------
  b.box(0, -1, 4, 170, 1, 120, wet);

  // ---- тело плотины -------------------------------------------------------
  // Верхняя часть (z от -36 до -28) сплошная — это сама плотина.
  b.box(0, 0, -32, DAM_X * 2, CREST_Y, 8, concrete);
  // Нижняя полоса гребня (z от -28 до -24) — с прорезами под лестницы.
  for (const [x0, x1] of spans()){
    b.box((x0 + x1) / 2, 0, -26, x1 - x0, CREST_Y, 4, concrete);
  }

  /**
   * Уступ водосливной грани.
   *
   * Высоты подобраны НЕ на глаз: они совпадают с высотой лестничного пандуса
   * на середине уступа. Если этого не сделать, сойти с лестницы на уступ можно,
   * а вернуться нельзя — этаж превращается в ловушку, и проверка проходимости
   * честно показывает такой уступ недостижимым.
   */
  function terrace(topY, z0, z1){
    for (const [x0, x1] of spans()){
      b.box((x0 + x1) / 2, 0, (z0 + z1) / 2, x1 - x0, topY, z1 - z0, concrete);
    }
    // мокрый след водослива на срезе — чтобы уступы читались с низу
    b.box(0, topY - 0.25, z1, DAM_X * 2, 0.25, 0.3, wet, "decor");
  }

  terrace(12.2, -24, -18);
  terrace( 8.3, -18, -12);
  terrace( 4.5, -12,  -6);

  // ---- лестницы в прорезах ------------------------------------------------
  // Один сплошной пандус от русла до гребня. Он же и заполняет прорез: ramp
  // строит коробки от земли, так что дыры в плотине не остаётся.
  for (const cx of CUTS){
    b.ramp(cx, 0, -2, cx, CREST_Y, -27, CUT_W - 1, concrete);
    // поручни по краям прореза — вид и ориентир, куда бежать
    for (const s of [-1, 1]){
      for (let z = -4; z >= -26; z -= 4){
        const y = CREST_Y * (-2 - z) / 25;
        b.box(cx + s * (CUT_W / 2 - 0.2), y, z, 0.25, 1.0, 0.25, steel, "decor");
      }
    }
  }

  // ---- парапет на гребне --------------------------------------------------
  // Невысокий: присел — укрылся, встал — виден. Разрывы ровно над прорезами.
  for (const [x0, x1] of spans()){
    b.box((x0 + x1) / 2, CREST_Y, -35.2, x1 - x0, 1.1, 0.5, concrete);
    b.box((x0 + x1) / 2, CREST_Y, -24.6, x1 - x0, 1.1, 0.5, concrete);
  }
  // фонарные мачты вдоль гребня — у самого парапета, чтобы не торчать на
  // проходе: мачта посреди дороги перекрывает пол-экрана и мешает, а не украшает
  for (let x = -44; x <= 44; x += 22){
    b.box(x, CREST_Y, -34.6, 0.4, 7, 0.4, steel);
    b.box(x, CREST_Y + 7, -34.6, 2.2, 0.3, 0.6, steel, "decor");
  }
  // Укрытия на гребне. Без них дорога поверху — чистый тир: кто первым увидел,
  // тот и выиграл. Шкафы и будка дают чем прикрыться на бегу.
  for (const s of [-1, 1]){
    b.box(s * 12, CREST_Y, -29, 2.2, 1.9, 1.6, steel);
    b.box(s * 40, CREST_Y, -30, 1.8, 1.9, 1.6, steel);
    b.box(s * 26, CREST_Y, -31, 4.6, 2.8, 4.0, concrete);      // будка обходчика
  }

  // ---- водохранилище выше плотины (только вид) -----------------------------
  b.box(0, 0, -66, 150, 13, 60, water, "decor");
  for (const s of [-1, 1]){
    b.box(s * 24, CREST_Y - 3, -37.5, 5, 6, 3, steel);        // башни водозабора
    b.box(s * 24, CREST_Y + 3, -37.5, 6, 0.6, 4, steel, "decor");
  }

  // ---- машинный зал в русле -----------------------------------------------
  const HALL_Z = 22, HALL_Y = 9;
  // стены: длинные глухие, в торцах и со стороны плотины — проёмы
  for (const s of [-1, 1]) b.box(s * 16.5, 0, HALL_Z, 3, HALL_Y, 20, concrete);
  for (const s of [-1, 1]){
    b.box(-11, 0, HALL_Z + s * 9.5, 11, HALL_Y, 2.4, concrete);
    b.box( 11, 0, HALL_Z + s * 9.5, 11, HALL_Y, 2.4, concrete);
    b.box(  0, 5.4, HALL_Z + s * 9.5, 11, HALL_Y - 5.4, 2.4, concrete);   // перемычка
  }
  b.box(0, HALL_Y, HALL_Z, 36, 0.6, 21, rust);                 // крыша
  for (let x = -14; x <= 14; x += 7){                          // фонари крыши
    b.box(x, HALL_Y + 0.6, HALL_Z, 2.2, 1.2, 15, steel, "decor");
  }
  // генераторы внутри: укрытия, чтобы зал не был пустой коробкой
  for (const x of [-9, 0, 9]){
    b.cylinder(x, 0, HALL_Z, 2.4, 2.6, steel);
    b.cylinder(x, 2.6, HALL_Z, 1.4, 1.2, rust, "decor");
  }
  // лестница на крышу зала — единственная высота в низу
  b.ramp(23, 0, HALL_Z + 14, 23, HALL_Y + 0.6, HALL_Z + 1, 3.4, rust);
  b.box(19.6, HALL_Y, HALL_Z - 2, 4, 0.6, 5, rust);

  // ---- напорные трубопроводы от плотины к залу ----------------------------
  for (const x of [-12, 0, 12]){
    b.box(x, 0, 4, 3.2, 2.8, 18, rust);
    for (const z of [-2, 4, 10]) b.box(x, 0, z, 4.0, 3.0, 1.0, rust, "decor");
  }

  // ---- водосбросные каналы по краям ---------------------------------------
  for (const s of [-1, 1]){
    const cx = 39 * s;
    b.box(cx - 4.5 * s, 0, 16, 1.6, 3.2, 46, concrete);
    b.box(cx + 4.5 * s, 0, 16, 1.6, 3.2, 46, concrete);
    // пороги в канале: единственные укрытия на всю длину
    for (const z of [0, 14, 28]) b.box(cx, 0, z, 7.4, 1.0, 1.4, wet);
  }

  // ---- открытая подстанция: укрытия в русле --------------------------------
  for (const s of [-1, 1]){
    for (let i = 0; i < 3; i++){
      const x = s * (26 + i * 0.5), z = 36 + i * 6;
      b.box(x, 0, z, 4.2, 3.0, 4.2, steel);
      b.box(x, 3.0, z, 1.0, 1.6, 1.0, steel, "decor");
    }
  }
  // штабели труб у выхода из канала
  for (const s of [-1, 1]) for (const z of [30, 40]){
    b.box(s * 48, 0, z, 3.0, 1.6, 8, rust);
  }

  // ---- козловой кран над руслом: ориентир ---------------------------------
  for (const s of [-1, 1]) b.box(s * 30, 0, 44, 1.2, 11, 1.2, steel);
  b.box(0, 11, 44, 62, 1.2, 2.2, steel, "decor");

  b.walls(-60, 60, -37, 50, 44);

  // ---- свет: пасмурный день, всё читается --------------------------------
  // Бетон сам по себе серый, и на пасмурном свете карта легко превращается в
  // кашу. Поэтому небесная подсветка холодная, солнце тёплое и низкое — так
  // уступы дают чёткие горизонтальные тени и этажи отличаются на глаз.
  b.light(new THREE.HemisphereLight(0xcdd9e4, 0x4e5450, 1.35));

  const sun = new THREE.DirectionalLight(0xffe8cd, 1.9);
  sun.position.set(60, 52, 40);
  sun.castShadow = true;
  sun.shadow.mapSize.set(2048, 2048);
  sun.shadow.camera.left = -80; sun.shadow.camera.right = 80;
  sun.shadow.camera.top = 80;   sun.shadow.camera.bottom = -80;
  sun.shadow.camera.far = 220;
  sun.shadow.bias = -0.0014;
  b.light(sun);

  return {
    group: b.group,
    colliders: b.colliders,
    sky: 0x9fb2bf,
    fog: { color: 0xa9bac5, near: 40, far: 185 },
    // A — машинный зал внизу, под крышей и с двумя входами. B — на гребне,
    // наверху: добежать туда можно только через прорез, и спецназ это знает.
    // Разница высот в шестнадцать метров делает точки не похожими совсем.
    //
    // Точка A стоит на z = 27, а не в середине зала: ровно по центру (x = 0,
    // z = 22) стоит генератор — цилиндр радиуса 2.4, и точка оказалась бы
    // внутри железа. Пять метров назад, между генератором и задней стеной, —
    // ровный пол, куда и кладут бомбу.
    sites: [[0, 0.1, 27], [0, CREST_Y + 0.1, -30]],
    spawns: spawnsFacing(FOCUS, [
      [-48, CREST_Y + 0.1, -30],
      [ 45, 0.1, 42],
      [ 48, CREST_Y + 0.1, -30],
      [-45, 0.1, 42],
      [  0, 0.1, 44],
      [ 15, 8.4, -15]
    ]),
    teamSpawns: {
      a: spawnsFacing(FOCUS, [[-48, CREST_Y + 0.1, -30], [-45, 0.1, 42], [-15, 8.4, -15]]),
      b: spawnsFacing(FOCUS, [[ 48, CREST_Y + 0.1, -30], [ 45, 0.1, 42], [ 15, 8.4, -15]])
    },
    build: b
  };
}
