// depo.js — «Депо».
//
// Ночное грузовое депо. Зеркально симметричная, тесная, с короткими
// дистанциями — полная противоположность «Карьеру». Там выигрывает тот, кто
// первым занял высоту и держит линию; здесь — тот, кто лучше знает, за каким
// вагоном кто стоит.
//
// Как она устроена и почему:
//
//   Поворотный круг. Открытый пятачок ровно в центре, куда сходятся все пути.
//              Пересекать его страшно и быстро, обходить — безопасно и долго.
//              Вся карта построена вокруг этого выбора.
//   Вагоны.    Ряды товарных вагонов образуют коридоры. Часть вагонов открыта
//              насквозь: сквозные проходы известны обеим сторонам и служат
//              короткой дорогой, но простреливаются вдоль.
//   Эстакада.  Мостки обслуживания поверху связывают обе стороны. Сверху видно
//              коридоры между вагонами — но снизу видно и тебя, а укрыться на
//              мостках негде.
//   Тупики.    Два зеркальных двора по краям, у каждого своё возрождение.
//
// Симметрия здесь обязательна: в командном режиме несимметричная карта всегда
// кому-то подыгрывает.

import { MapBuilder, THREE, rough, yawTowards } from "./builder.js";

export const meta = {
  id: "depo",
  name: "Депо",
  subtitle: "Ночь, вагоны, поворотный круг в центре",
  hint: "Центр открыт со всех сторон. Обходи вагонами или лезь на эстакаду."
};

const ASPHALT = 0x3c3f3e;
const CAR_A   = 0x7d5745;   // сурик
const CAR_B   = 0x4c5a53;   // зелёный вагон
const STEEL   = 0x666d71;
const CONCRETE= 0x585851;

// Все смотрят на поворотный круг — центр карты и центр всей драки.
const TURNTABLE = [0, 0, 0];
const spawnsFacing = (focus, list) =>
  list.map(pos => ({ pos, yaw: yawTowards(pos, focus) }));

export function build(){
  const b = new MapBuilder();

  const ground   = rough(ASPHALT, { roughness: 0.98 });
  const carA     = rough(CAR_A, { roughness: 0.85, metalness: 0.2 });
  const carB     = rough(CAR_B, { roughness: 0.85, metalness: 0.2 });
  const steel    = rough(STEEL, { roughness: 0.5, metalness: 0.55 });
  const concrete = rough(CONCRETE);
  const rail     = rough(0x6e6357, { roughness: 0.4, metalness: 0.6 });

  // ---- земля --------------------------------------------------------------
  b.box(0, -1, 0, 150, 1, 110, ground);

  // рельсы: чистая декорация, но без них депо не депо
  for (const z of [-34, -17, 0, 17, 34]){
    b.box(0, 0, z - 0.72, 140, 0.16, 0.16, rail, "decor");
    b.box(0, 0, z + 0.72, 140, 0.16, 0.16, rail, "decor");
  }

  // ---- поворотный круг в центре ------------------------------------------
  b.cylinder(0, 0, 0, 13, 0.35, concrete, "decor");
  const ring = new THREE.Mesh(
    new THREE.RingGeometry(12.4, 13.2, 40),
    new THREE.MeshStandardMaterial({ color: 0x8a7a44, roughness: 0.6, metalness: 0.4 })
  );
  ring.rotation.x = -Math.PI / 2;
  ring.position.y = 0.38;
  b.group.add(ring);
  // ферма поворотного круга — единственное укрытие в центре, низкое
  b.box(0, 0.35, 0, 26, 1.1, 1.4, steel);
  b.box(0, 1.45, -6, 1.2, 1.6, 1.2, steel);
  b.box(0, 1.45,  6, 1.2, 1.6, 1.2, steel);

  /**
   * Ряд вагонов. gap — номер вагона, который стоит с открытыми дверями:
   * сквозной проход, который обе стороны знают и обе им пользуются.
   */
  function carRow(z, startX, count, material, gap = -1){
    for (let i = 0; i < count; i++){
      const x = startX + i * 15;
      if (i === gap){
        // открытый вагон: две половины и дыра посередине
        b.box(x - 4.6, 0, z, 4.8, 3.6, 3.2, material);
        b.box(x + 4.6, 0, z, 4.8, 3.6, 3.2, material);
        b.box(x, 3.6, z, 14, 0.3, 3.2, material);   // крыша над проходом
      } else {
        b.box(x, 0, z, 14, 3.6, 3.2, material);
      }
      b.box(x - 5, 0, z, 1.2, 0.5, 3.6, steel, "decor");   // тележки
      b.box(x + 5, 0, z, 1.2, 0.5, 3.6, steel, "decor");
    }
  }

  // Зеркально: левая и правая стороны одинаковы с точностью до знака x.
  for (const side of [-1, 1]){
    carRow(-34 * side, 22 * side, 3, carA, 1);
    carRow(-17 * side, 30 * side, 2, carB, 0);
    carRow( 17 * side, 26 * side, 3, carB, 2);
    carRow( 34 * side, 34 * side, 2, carA, -1);
  }

  // ---- тупики по краям: возрождение --------------------------------------
  for (const side of [-1, 1]){
    const x = 64 * side;
    b.box(x, 0, 0, 3, 6, 46, concrete);                 // торцевая стена
    b.box(x - 6 * side, 0, -24, 9, 4, 9, concrete);     // будка
    b.box(x - 6 * side, 0,  24, 9, 4, 9, concrete);
    b.box(x - 2 * side, 0, 0, 2.4, 1.2, 2.4, carA);     // штабель шпал
  }

  // ---- эстакада обслуживания поверху -------------------------------------
  const EZ = -46;
  b.box(0, 7, EZ, 130, 0.4, 4, steel);
  for (let x = -60; x <= 60; x += 15) b.box(x, 0, EZ, 0.6, 7, 0.6, steel);   // опоры
  for (let x = -62; x <= 62; x += 4){                                        // перила
    b.box(x, 7.4, EZ - 1.9, 0.3, 1.1, 0.3, steel, "decor");
  }
  // Лестницы с обоих концов — симметрия соблюдена.
  // x = 62, а не 56: на 56 лестница упиралась бы в крайний вагон ряда z = -34,
  // а короткий подъём пришлось бы делать почти отвесным. Здесь ряды вагонов
  // кончаются на x = 59, места хватает, и наклон выходит пологим — примерно
  // 28 градусов вместо 46.
  for (const side of [-1, 1]){
    b.ramp(62 * side, 0, EZ + 16, 62 * side, 7.4, EZ + 2, 3.4, steel);
  }
  // сходни с эстакады на крыши ближних вагонов: путь наверх есть и из центра
  // base = 3.7: сходни идут поверх крыши вагона, а не от самой земли.
  b.ramp(0, 7.4, EZ + 2, 0, 3.9, EZ + 10, 3, steel, 3.7, 10);
  b.box(0, 0, EZ + 13, 16, 3.9, 3.2, carB);

  // ---- водонапорная башня: ориентир, видно отовсюду -----------------------
  b.cylinder(-52, 0, 40, 1.1, 12, steel);
  b.cylinder(-52, 12, 40, 4.5, 6, rough(0x6a4a3c, { roughness: 0.9 }));
  b.box(-52, 18, 40, 10, 0.5, 10, steel, "decor");

  b.walls(-72, 72, -56, 56, 30);

  // ---- свет: ночь под натриевыми фонарями --------------------------------
  //
  // Начиная с Three r155 яркость источников считается физически: у точечного
  // света она задаётся в канделах и падает пропорционально квадрату
  // расстояния. Привычные по старым примерам числа вроде intensity: 40 дают
  // на десяти метрах меньше половины единицы — карта выходит непроглядно
  // чёрной. Отсюда сотни ниже: это не "ярко", это правильный порядок величины.
  //
  // Общий свет держим достаточным, чтобы силуэт бойца читался и в тени: ночь
  // на карте нужна ради настроения и укрытий, а не ради того, чтобы игрок
  // вглядывался в чёрный экран.
  b.light(new THREE.HemisphereLight(0x4a5a6e, 0x1c2024, 1.25));

  const moon = new THREE.DirectionalLight(0xa8c0dc, 0.75);
  moon.position.set(-40, 70, -50);
  moon.castShadow = true;
  moon.shadow.mapSize.set(2048, 2048);
  moon.shadow.camera.left = -80; moon.shadow.camera.right = 80;
  moon.shadow.camera.top = 70;   moon.shadow.camera.bottom = -70;
  moon.shadow.camera.far = 200;
  moon.shadow.bias = -0.0015;
  b.light(moon);

  // Фонари на мачтах: тёплые пятна, между ними полумрак — в нём и прячутся.
  for (const [x, z] of [[0, 0], [-34, -20], [34, -20], [-34, 20], [34, 20], [0, -44], [-58, 0], [58, 0]]){
    b.box(x, 0, z, 0.5, 11, 0.5, steel);
    b.box(x, 11, z, 1.6, 0.4, 1.6, steel, "decor");
    const lamp = new THREE.PointLight(0xffb45c, 900, 52, 2);
    lamp.position.set(x, 10.4, z);
    b.light(lamp);
  }

  return {
    group: b.group,
    colliders: b.colliders,
    sky: 0x0d1117,
    fog: { color: 0x0e1319, near: 30, far: 155 },
    // Возрождение. Раньше точки стояли ровно там, где будки в тупиках, — то
    // есть боец появлялся на крыше четырёхметровой коробки и слезть не мог.
    // Проверено обходом карты: все точки связаны между собой.
    spawns: spawnsFacing(TURNTABLE, [
      [-57, 0.1,   8],
      [ 57, 0.1,  -8],
      [-57, 0.1,  -8],
      [ 57, 0.1,   8],
      [  0, 7.6, -46],   // эстакада
      [-40, 0.1,  46]    // у водонапорной башни
    ]),
    // Командный режим: тупик против тупика, круг посередине — ничей.
    teamSpawns: {
      a: spawnsFacing(TURNTABLE, [[-57, 0.1, 8], [-57, 0.1, -8]]),
      b: spawnsFacing(TURNTABLE, [[57, 0.1, -8], [57, 0.1, 8]])
    },
    build: b
  };
}
