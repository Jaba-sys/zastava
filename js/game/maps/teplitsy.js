// teplitsy.js — «Теплицы».
//
// Заброшенный тепличный комбинат ранним утром. Карта построена вокруг одного
// приёма, которого нет ни на «Карьере», ни в «Депо»: СТЕКЛО.
//
// Стеклянная стена не пускает человека, но пропускает пулю. Значит, тут впервые
// «вижу» и «могу выстрелить» перестают совпадать с «могу дойти». Ты видишь
// противника через три теплицы, он видит тебя, вы стреляете друг в друга — а
// добежать можно только в обход, через двери на торцах. Держать угол здесь
// бесполезно: угол простреливается насквозь.
//
// Отсюда и остальное устройство:
//
//   Четыре теплицы. Стоят квадратом вокруг двора. Внутри — гряды по пояс:
//              единственное настоящее укрытие, потому что они непрозрачные.
//              Присел за грядой — тебя нет; встал — ты виден из всех четырёх
//              теплиц сразу.
//   Двор.      Центр с котельной. Котельная глухая, кирпичная — единственное
//              место на карте, где стена действительно защищает. За неё и
//              дерутся.
//   Крыша котельной. Высота, с которой простреливаются все четыре теплицы
//              сверху. Подъём один, по наружному пандусу, и он на виду.
//   Обход по краю. Вдоль ограды идут дорожки за глухими штабелями поддонов —
//              длинный безопасный путь для тех, кто не хочет в стекло.
//
// Симметрия зеркальная по обеим осям: в командном режиме ни одна сторона не
// получает лучшего стекла.

import { MapBuilder, THREE, rough, yawTowards, glass } from "./builder.js";

export const meta = {
  id: "teplitsy",
  name: "Теплицы",
  subtitle: "Утро, стекло и гряды: тебя видно насквозь",
  hint: "Стекло держит человека, но не пулю. Укрытие тут только гряда и котельная."
};

const SOIL     = 0x574b39;
const PATH     = 0x6e6656;
const BRICK    = 0x8a5c47;
const FRAME    = 0xb9c3c0;   // белая алюминиевая рама
const BED      = 0x3d3327;
const GREEN    = 0x4e6b37;
const RUST     = 0x7a5138;

const BOILER = [0, 0, 0];
const spawnsFacing = (focus, list) =>
  list.map(pos => ({ pos, yaw: yawTowards(pos, focus) }));

export function build(){
  const b = new MapBuilder();

  const soil  = rough(SOIL, { roughness: 0.99 });
  const path  = rough(PATH, { roughness: 0.95 });
  const brick = rough(BRICK, { roughness: 0.9 });
  const frame = rough(FRAME, { roughness: 0.45, metalness: 0.5 });
  const bed   = rough(BED, { roughness: 1 });
  const green = rough(GREEN, { roughness: 1 });
  const rust  = rough(RUST, { roughness: 0.8, metalness: 0.3 });
  const pane  = glass(0xc8e4e6);

  // ---- земля --------------------------------------------------------------
  b.box(0, -1, 0, 170, 1, 140, soil);
  // дорожки между теплицами — просто чтобы глаз читал план комбината
  b.box(0, 0, 0, 150, 0.04, 9, path, "decor");
  b.box(0, 0, 0, 9, 0.04, 120, path, "decor");

  /**
   * Одна теплица.
   *
   * Низ кирпичный (по колено), верх стеклянный до самой крыши. Двери — на
   * торцах, по оси x: сквозной проход насквозь есть всегда, иначе теплица
   * превращается в аквариум, из которого не выбраться под огнём.
   *
   * Крыша сделана декорацией СПЕЦИАЛЬНО. Стеклянная крыша-коллайдер была бы
   * потолком на четырёх метрах, по которому можно бегать, — а лазить туда
   * неоткуда, и проверка проходимости справедливо ругалась бы на висящий в
   * воздухе этаж. Здесь крыша только для вида и для света.
   *
   * broken — номера секций боковой стены, где стекло выбито: настоящие дыры,
   * через которые можно войти. Каждая теплица ломается по-своему, чтобы карта
   * не читалась как четыре одинаковых коробки.
   */
  function greenhouse(cx, cz, broken = []){
    const W = 34, D = 22, SILL = 0.9, TOP = 3.9;
    const halfW = W / 2, halfD = D / 2;
    const DOOR = 3.6;

    // Торцы (стены, перпендикулярные x): две секции и дверь посередине.
    for (const sx of [-1, 1]){
      const x = cx + halfW * sx;
      const seg = (D - DOOR) / 2;
      for (const sz of [-1, 1]){
        const z = cz + sz * (DOOR / 2 + seg / 2);
        b.box(x, 0, z, 0.35, SILL, seg, brick);
        b.box(x, SILL, z, 0.25, TOP - SILL, seg, pane, "glass");
      }
      // косяк двери
      b.box(x, 0, cz - DOOR / 2, 0.4, TOP, 0.3, frame);
      b.box(x, 0, cz + DOOR / 2, 0.4, TOP, 0.3, frame);
      b.box(x, TOP, cz, 0.4, 0.3, DOOR, frame);
    }

    // Боковины: восемь секций, часть — выбитые.
    const SEG = W / 8;
    for (let i = 0; i < 8; i++){
      const x = cx - halfW + SEG / 2 + i * SEG;
      for (const sz of [-1, 1]){
        const z = cz + halfD * sz;
        b.box(x, 0, z, SEG, SILL, 0.35, brick);
        if (!broken.includes(i)){
          b.box(x, SILL, z, SEG, TOP - SILL, 0.25, pane, "glass");
        }
      }
    }

    // Рама: стойки и конёк. Стойки непрозрачные — узкие столбики, за которыми
    // не спрячешься, но по ним читается глубина.
    for (let i = 0; i <= 8; i++){
      const x = cx - halfW + i * SEG;
      for (const sz of [-1, 1]) b.box(x, 0, cz + halfD * sz, 0.18, TOP, 0.3, frame);
    }

    // Крыша — двускатная, только на вид.
    b.box(cx, TOP, cz - halfD / 2, W, 0.14, D / 2 + 0.6, pane, "decor");
    b.box(cx, TOP, cz + halfD / 2, W, 0.14, D / 2 + 0.6, pane, "decor");
    b.box(cx, TOP + 0.5, cz, W, 0.9, 1.0, frame, "decor");
    for (const sz of [-1, 1]) b.box(cx, TOP, cz + halfD * sz, W, 0.6, 0.25, frame, "decor");

    // Гряды внутри: ДВА ряда вдоль, проход посередине и по краям.
    // Высота 1.05 — присел (1.1) и скрылся целиком, встал и виден.
    for (const sz of [-1, 1]){
      const z = cz + sz * 5.4;
      b.box(cx, 0, z, W - 5, 1.05, 3.0, bed);
      b.box(cx, 1.05, z, W - 5.4, 0.45, 2.6, green, "decor");
    }
    // поперечный разрыв в грядах: через теплицу можно пройти и поперёк
    for (const sz of [-1, 1]){
      const z = cz + sz * 5.4;
      b.box(cx, 0, z, 3.2, 1.2, 3.4, soil, "decor");   // вид: земля вместо зелени
    }

    // Бочки с водой по углам — низкое непрозрачное укрытие у самых дверей.
    for (const sx of [-1, 1]) for (const sz of [-1, 1]){
      b.cylinder(cx + sx * (halfW - 3), 0, cz + sz * (halfD - 2.4), 0.8, 1.2, rust);
    }
  }

  greenhouse(-40, -30, [2, 3]);
  greenhouse( 40, -30, [4, 5]);
  greenhouse(-40,  30, [4, 5]);
  greenhouse( 40,  30, [2, 3]);

  // ---- котельная во дворе -------------------------------------------------
  // Глухая кирпичная коробка. Внутри пусто и есть два входа насквозь: коробка
  // без входов была бы просто столбом, а так это ещё и проходной узел.
  const BH = 6.5;
  for (const sx of [-1, 1]){
    b.box(sx * 8.8, 0, 0, 2.4, BH, 16, brick);            // длинные стены
  }
  for (const sz of [-1, 1]){
    // торец с проёмом посередине
    b.box(-6.0, 0, sz * 7.6, 6.0, BH, 1.6, brick);
    b.box( 6.0, 0, sz * 7.6, 6.0, BH, 1.6, brick);
    b.box(0, 4.2, sz * 7.6, 6.0, 2.3, 1.6, brick);        // перемычка над проёмом
  }
  b.box(0, BH, 0, 20, 0.5, 17, rust);                      // крыша
  b.box(0, BH + 0.5, 0, 20, 0.9, 0.4, rust, "decor");      // парапет — только вид
  b.cylinder(-7, BH, -6, 1.3, 9, brick);                   // труба
  b.cylinder(-7, BH + 9, -6, 1.5, 0.5, rust, "decor");

  // Пандус на крышу: один, снаружи, с восточной стороны — виден отовсюду.
  b.ramp(16, 0, 9, 16, BH + 0.5, -4, 3.2, rust);
  b.box(13.2, BH, 2.5, 3.4, 0.5, 14, rust);                // площадка к крыше
  b.box(11.2, BH, 0, 2.6, 0.5, 6, rust);

  // ---- двор: укрытия между котельной и теплицами --------------------------
  for (const sx of [-1, 1]) for (const sz of [-1, 1]){
    const x = 17 * sx, z = 15 * sz;
    b.box(x, 0, z, 3.2, 1.5, 2.2, rust);                   // штабель ящиков
    b.box(x + 1.2 * sx, 1.5, z, 2.0, 1.0, 1.8, rust);
  }
  // Длинная теплотрасса через двор: труба на низких опорах. Перепрыгнуть можно,
  // спрятаться за ней — тоже; и она делит двор надвое по диагонали взгляда.
  for (const sx of [-1, 1]){
    b.box(sx * 30, 0, 0, 22, 1.3, 1.6, rust);
    for (const x of [-8, 0, 8]) b.box(sx * 30 + x, 0, 0, 1.0, 1.3, 2.6, rust, "decor");
  }

  // ---- дорожки по краю за поддонами ---------------------------------------
  for (const sz of [-1, 1]){
    for (let x = -54; x <= 54; x += 13){
      b.box(x, 0, sz * 56, 5.5, 2.0, 2.4, rust);           // штабели поддонов
    }
  }
  for (const sx of [-1, 1]){
    for (let z = -44; z <= 44; z += 13){
      b.box(sx * 66, 0, z, 2.4, 2.0, 5.5, rust);
    }
  }

  // ---- ориентир: водонапорная башня у северо-запада ------------------------
  b.cylinder(-62, 0, -56, 1.0, 11, rust);
  b.cylinder(-62, 11, -56, 3.6, 5, rough(0x6f7a6a, { roughness: 0.9 }));

  b.walls(-76, 76, -64, 64, 30);

  // ---- свет: раннее утро, низкое солнце сквозь стекло ----------------------
  // Солнце намеренно низкое и почти вдоль теплиц: длинные тени от рам ложатся
  // поперёк проходов, и карта читается объёмной, а не как чертёж.
  b.light(new THREE.HemisphereLight(0xdfe9f2, 0x6b6047, 1.5));

  const sun = new THREE.DirectionalLight(0xffe6c0, 2.0);
  sun.position.set(-70, 42, -34);
  sun.castShadow = true;
  sun.shadow.mapSize.set(2048, 2048);
  sun.shadow.camera.left = -90; sun.shadow.camera.right = 90;
  sun.shadow.camera.top = 80;   sun.shadow.camera.bottom = -80;
  sun.shadow.camera.far = 240;
  sun.shadow.bias = -0.0014;
  b.light(sun);

  return {
    group: b.group,
    colliders: b.colliders,
    sky: 0xbcd0dc,
    fog: { color: 0xc6d6de, near: 45, far: 190 },
    spawns: spawnsFacing(BOILER, [
      [-62, 0.1, -12],
      [ 62, 0.1,  12],
      [-62, 0.1,  12],
      [ 62, 0.1, -12],
      [  0, 0.1, -48],
      [  0, 0.1,  48]
    ]),
    teamSpawns: {
      a: spawnsFacing(BOILER, [[-62, 0.1, -12], [-62, 0.1, 12], [-40, 0.1, -46]]),
      b: spawnsFacing(BOILER, [[ 62, 0.1,  12], [ 62, 0.1, -12], [ 40, 0.1,  46]])
    },
    build: b
  };
}
